CATALOGS = {"fa-ir": FA_IR, "fa": FA_IR}


def _language_code() -> str:
    code = str(getattr(settings, "LANGUAGE_CODE", "fa-ir") or "fa-ir").lower()
    return code if code in CATALOGS else code.split("-")[0]


def translate(key: str, **params) -> str:
    """Return a translated string for *key* and interpolate named parameters."""
    catalog = CATALOGS.get(_language_code(), FA_IR)
    template = catalog.get(key)
    if template is None:
        raise KeyError(f"Unknown translation key: {key}")
    return template.format(**params) if params else template


def translation_bundle(scope: str) -> dict[str, str]:
    """Return browser translations below ``js.<scope>.`` with the prefix removed."""
    prefix = f"js.{scope}."
    return {key[len(prefix):]: value for key, value in FA_IR.items() if key.startswith(prefix)}


def has_translation(key: str) -> bool:
    return key in FA_IR
